def test_corpus_is_populated():
    assert len(TRACES) >= 10, "the golden corpus is the G1 safety net; keep it broad"
    assert "fast_improver" in TRACE_IDS
    assert "non_improver" in TRACE_IDS
    assert "alternating_corner" in TRACE_IDS


