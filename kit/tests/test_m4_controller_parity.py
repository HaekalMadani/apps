def expected(trace):
    return normalise({
        "events": trace["expected_events"],
        "disabled": trace["expected_disabled_elements"],
        "final": trace["expected_final_state"],
    })


@pytest.mark.parametrize("path", TRACES, ids=TRACE_IDS)
def test_python_matches_committed_expectations(path):
    trace = load_trace(path)
    got, want = run_python(trace), expected(trace)
    assert got["events"] == want["events"]
    assert got["final"] == want["final"]
    assert got["disabled"] == want["disabled"]


