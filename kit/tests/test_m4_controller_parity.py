def test_reversion_cap_pins_the_element_at_reduced():
    trace = trace_named("erratic_cap_reached")
    result = run_python(trace)
    cap = merged_config(trace)["probe"]["reversion_cap"]
    for element in ("braking", "corner_speed", "apex"):
        seq = transitions(trace, element)
        assert seq[-2:] == ["probe_to_revert", "cap_reached"]
        assert seq.count("probe_to_revert") == cap
        el = result["final"][element]
        assert el["pinned"] and el["stage"] == "reduced"
    # cap_reached must be stamped with the reversion count that triggered it.
    cap_events = [e for e in result["events"] if e["transition"] == "cap_reached"]
    assert all(e["reversion_count"] == cap for e in cap_events)


def test_one_regression_never_costs_two_stages():
    """A reversion must not cascade on the same sub-threshold share.

    Found by the corpus: without disarming, a probe reversion left the element at
    reduced with the share that caused it, so the next pass reverted it again to
    full — and the reversion cap could then never be reached.
    """
    for name in ("erratic_cap_reached", "staggered_regression"):
        events = run_python(trace_named(name))["events"]
        by_element = {}
        for e in events:
            by_element.setdefault(e["element"], []).append(e)
        for element_events in by_element.values():
            reverts = ("probe_to_revert", "reduced_to_full")
            for a, b in zip(element_events, element_events[1:]):
                if a["transition"] in reverts and b["transition"] in reverts:
                    assert b["lap"] > a["lap"] + 1, (
                        "{} cascaded {} -> {} on consecutive passes".format(
                            name, a["transition"], b["transition"]))


def test_staggered_regression_reverts_the_probe():
    """Eval plan target 3, on the honest (staggered) stream."""
    trace = trace_named("staggered_regression")
    seq = transitions(trace)
    assert "probe_to_revert" in seq
    revert = next(e for e in events_of(trace) if e["transition"] == "probe_to_revert")
    probe_entry = next(e for e in events_of(trace) if e["transition"] == "reduced_to_probe")
    # Regression begins the lap after the probe is entered, so the reversion
    # lands within the probe's own length -- the first lap the evidence can
    # support a verdict. Read from the trace's pinned config, not the live file.
    assert (revert["lap"] - probe_entry["lap"]
            <= merged_config(trace)["probe"]["laps"])


def test_a_null_criterion_stalls_an_element_rather_than_fading_it():
    """The conservative direction of the null-is-no-evidence rule."""
    trace = trace_named("null_criteria_stall")
    result = run_python(trace)
    assert not any(e["element"] == "braking" for e in result["events"])
    assert result["final"]["braking"]["stage"] == "full"
    # A null must not count as a failure: no window may hold an entry for the
    # corner that produced only nulls.
    corner_3 = next(c for c in result["final"]["braking"]["corners"] if c["corner_id"] == "3")
    assert corner_3["window"] == [] and corner_3["consec_fail"] == 0
    # The elements with real evidence are untouched by the stalled one.
    assert transitions(trace, "corner_speed")[-1] == "probe_to_removed"


def test_hysteresis_dead_band_holds_the_stage():
    """Between the 0.5 and 0.75 thresholds the element must not move at all."""
    trace = trace_named("reduced_to_full_revert")
    seq = transitions(trace)
    assert seq == ["full_to_reduced", "reduced_to_full"]
    ev = events_of(trace)
    # Several laps pass at a qualified share of exactly 0.5 between the two.
    assert ev[1]["lap"] - ev[0]["lap"] >= 4


def test_events_within_a_pass_are_emitted_in_element_order():
    """Two implementations must order simultaneous events identically."""
    from trace_kit.controller import ELEMENTS
    for path in TRACES:
        events = run_python(load_trace(path))["events"]
        by_pass = {}
        for e in events:
            by_pass.setdefault((e["lap"], e["t"]), []).append(e["element"])
        for elements in by_pass.values():
            # One element may emit two events on a pass (probe_to_revert then
            # cap_reached), so collapse runs before comparing: what must hold is
            # that the DISTINCT elements appear in ELEMENTS order.
            runs = [e for i, e in enumerate(elements) if i == 0 or e != elements[i - 1]]
            assert runs == [e for e in ELEMENTS if e in runs], (
                "{}: events out of element order: {}".format(path.name, elements))


def test_no_element_ever_skips_a_stage():
    """Transitions move ONE stage at a time, in either direction (framing v6)."""
    legal = {
        "full_to_reduced": ("full", "reduced"),
        "reduced_to_probe": ("reduced", "probe"),
        "probe_to_removed": ("probe", "removed"),
        "probe_to_revert": ("probe", "reduced"),
        "reduced_to_full": ("reduced", "full"),
    }
    for path in TRACES:
        stage = {"braking": "full", "corner_speed": "full", "apex": "full"}
        for e in run_python(load_trace(path))["events"]:
            if e["transition"] in ("censored", "cap_reached"):
                continue
            src, dst = legal[e["transition"]]
            assert stage[e["element"]] == src, "{}: {} fired from {}".format(
                path.name, e["transition"], stage[e["element"]])
            stage[e["element"]] = dst


def test_every_event_validates_against_the_fade_schema():
    """The controller's output IS the fades_<block>.jsonl record, minus stamps."""
    for path in TRACES:
        for e in run_python(load_trace(path))["events"]:
            record = dict(e, schema_version=1, block_id="GOLDEN")
            assert pyval.validate_data("fades", record) == [], record
