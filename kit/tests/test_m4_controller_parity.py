"""M4 golden-trace parity suite (impl plan section 6) — the gate on Gate G1.

The fading controller exists twice: ``lua/trace_rt/lib/controller.lua`` runs
inside Assetto Corsa and is what participants drive; ``trace_kit.controller``
runs the Phase 1 simulation that tunes and certifies it. A divergence between
them is the failure the impl plan singles out as silently invalidating G1 — the
simulation would certify a controller nobody experiences.

Three layers, in increasing order of independence:

1. **Corpus parity.** Every trace in ``golden_traces/`` is run through BOTH
   implementations and the event sequences and final states must match exactly.
   The Lua runs headless through lupa (LuaJIT 2.1, matching CSP), the same
   mechanism the M0 validator-parity suite uses.
2. **Corpus regression.** Both must also match the expectations COMMITTED in the
   trace files, so a change that moves both implementations together is still
   caught.
3. **Spec assertions.** Hand-written checks that read the traces' behaviour, not
   their stored blobs: the lap budget, event orderings, the pathologies. The
   committed expectations were generated by the Python implementation, so a bug
   there would have been baked into the corpus; these are what a regenerated
   corpus still has to get past.
"""

import json
from pathlib import Path

import pytest
from lupa.luajit21 import LuaRuntime

from trace_kit import validate as pyval
from trace_kit.controller import Controller

REPO_ROOT = Path(__file__).resolve().parents[2]
LUA_APP_DIR = REPO_ROOT / "lua" / "trace_rt"
GOLDEN_DIR = REPO_ROOT / "golden_traces"
BASE_CONFIG = json.loads((REPO_ROOT / "configs" / "controller_config.json").read_text("utf-8"))

TRACES = sorted(GOLDEN_DIR.glob("*.json"))
TRACE_IDS = [p.stem for p in TRACES]


def load_trace(path):
    return json.loads(path.read_text(encoding="utf-8"))


def merged_config(trace):
    cfg = json.loads(json.dumps(BASE_CONFIG))
    for section, values in trace.get("config_overrides", {}).items():
        cfg[section].update(values)
    return cfg


# --- runners -----------------------------------------------------------------

@pytest.fixture(scope="module")
def lua_run():
    """run(trace_json) -> {"events": [...], "disabled": [...], "final": {...}}.

    A thin Lua harness drives the REAL runtime module the same way trace_rt.lua
    will. Everything crosses the boundary as JSON text, so no lupa table-proxy
    quirk can quietly launder a difference between the two implementations.
    """
    lua = LuaRuntime(unpack_returned_tuples=True)
    lua.execute('package.path = "{}/?.lua;" .. package.path'.format(LUA_APP_DIR.as_posix()))
    return lua.eval(
        """
        function(trace_json, config_json)
          local json = require('lib/json')
          local controller = require('lib/controller')
          local trace = json.decode(trace_json)
          local cfg = json.decode(config_json)
          local st = controller.new(cfg, trace.applicable)
          local events = {}
          for i = 1, #trace.passes do
            local p = trace.passes[i]
            -- json.decode turns JSON null into json.null, a sentinel table.
            -- The controller's contract is Lua nil for "no evidence", so
            -- normalise here rather than teaching the controller about JSON.
            local crit = {}
            for _, e in ipairs(controller.ELEMENTS) do
              local v = p.criteria[e]
              if type(v) == 'boolean' then crit[e] = v end
            end
            local evs = controller.step(st, {
              corner_id = p.corner_id, lap = p.lap, t = p.t, criteria = crit,
            })
            for j = 1, #evs do events[#events + 1] = evs[j] end
          end
          if trace.finish ~= nil then
            local evs = controller.finish(st, trace.finish.lap, trace.finish.t)
            for j = 1, #evs do events[#events + 1] = evs[j] end
          end
          -- json.encode drops empty tables ambiguously, so hand back a shape the
          -- Python side can normalise identically for both implementations.
          return json.encode({
            events = events,
            disabled = controller.disabled_elements(st),
            final = controller.snapshot(st),
          })
        end
        """
    )


def normalise(result):
    """Make Lua-decoded and Python-native results structurally comparable.

    Lua has no empty-array/empty-object distinction, so an empty list can come
    back either way through JSON; every list-valued field is coerced to a list.
    """
    def as_list(v):
        return [] if v in (None, {}) else list(v)

    events = []
    for e in result["events"]:
        ev = {
            "element": e["element"],
            "transition": e["transition"],
            "t": e["t"],
            "lap": e["lap"],
            "quorum": {
                "qualified_share": e["quorum"]["qualified_share"],
                "qualified_corners": as_list(e["quorum"].get("qualified_corners")),
                "applicable_corners": e["quorum"]["applicable_corners"],
                "flipped_corners": as_list(e["quorum"].get("flipped_corners")),
            },
        }
        if "reversion_count" in e and e["reversion_count"] is not None:
            ev["reversion_count"] = e["reversion_count"]
        events.append(ev)

    final = {}
    for name, el in result["final"].items():
        final[name] = {
            "stage": el["stage"],
            "disabled": bool(el["disabled"]),
            "pinned": bool(el["pinned"]),
            "revert_armed": bool(el["revert_armed"]),
            "reversions": el["reversions"],
            "applicable_corners": el["applicable_corners"],
            "qualified_corners": as_list(el.get("qualified_corners")),
            "qualified_share": el["qualified_share"],
            "corners": [
                {
                    "corner_id": c["corner_id"],
                    "window": as_list(c.get("window")),
                    "consec_fail": c["consec_fail"],
                }
                for c in as_list(el.get("corners"))
            ],
        }
    return {"events": events, "disabled": as_list(result.get("disabled")), "final": final}


def run_python(trace):
    cfg = merged_config(trace)
    ctrl = Controller(cfg, trace["applicable"])
    events = []
    for p in trace["passes"]:
        events.extend(ctrl.step(p))
    if "finish" in trace:
        events.extend(ctrl.finish(trace["finish"]["lap"], trace["finish"]["t"]))
    return normalise({"events": events, "disabled": ctrl.disabled_elements(),
                      "final": ctrl.snapshot()})


def run_lua(lua_run, trace):
    out = json.loads(lua_run(json.dumps(trace), json.dumps(merged_config(trace))))
    return normalise(out)


